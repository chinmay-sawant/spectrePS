func TestRecoverHeadersInsideBadLengthStream(t *testing.T) {
	src, err := decodeHex(fixtureBadLengthStream)
	if err != nil {
		t.Fatal(err)
	}

	entries := scanObjectHeaders(src)
	for _, num := range []int{6, 7, 8, 10} {
		if _, ok := entries[num]; !ok {
			t.Errorf("object %d header was not indexed", num)
		}
	}

	file := mustOpen(t, src)
	if file.PageCount() != 1 {
		t.Fatalf("pages %d, want 1", file.PageCount())
	}
	info, err := file.Info()
	if err != nil {
		t.Fatal(err)
	}
	if info.Pages != 1 || info.PageSizes[0] != (PageSize{Width: 10, Height: 20}) {
		t.Fatalf("info %+v", info)
	}
}

func TestInfoScansPagesAfterSecondTreeFails(t *testing.T) {
	src, err := decodeHex(fixtureSecondTreeInfo)
	if err != nil {
		t.Fatal(err)
	}
	file := mustOpen(t, src)
	if file.PageCount() != 2 {
		t.Fatalf("pages %d, want 2", file.PageCount())
	}
	info, err := file.Info()
	if err != nil {
		t.Fatal(err)
	}
	if info.Pages != 2 || info.PageSizes[0] != (PageSize{Width: 100, Height: 200}) ||
		info.PageSizes[1] != (PageSize{Width: 50, Height: 60}) {
		t.Fatalf("info %+v", info)
	}
}

func TestOpenKeepsReachablePagesWhenTreeNamesStream(t *testing.T) {
	src, err := decodeHex(fixtureStreamKidTree)
	if err != nil {
		t.Fatal(err)
	}
	file := mustOpen(t, src)
	if file.PageCount() != 1 {
		t.Fatalf("pages %d, want 1", file.PageCount())
	}
	info, err := file.Info()
	if err != nil {
		t.Fatal(err)
	}
	if info.Pages != 1 {
		t.Fatalf("info pages %d, want 1", info.Pages)
	}
}

func TestScanObjectHeadersSkipsValidStreamPayload(t *testing.T) {
	src, err := decodeHex(fixtureValidLengthStream)
	if err != nil {
		t.Fatal(err)
	}
	entries := scanObjectHeaders(src)
	if _, ok := entries[99]; ok {
		t.Fatal("object-like stream data was indexed")
	}
}
