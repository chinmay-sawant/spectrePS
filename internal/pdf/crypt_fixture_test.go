// encryptFixtures returns every fixture with its handler revision and the
// words its content stream draws.
func encryptFixtures() []struct {
	name string
	hex  string
} {
	return []struct {
		name string
		hex  string
	}{
		{"R2, RC4-40, /V 1", fixtureRC440},
		{"R3, RC4-128, /V 2", fixtureRC4128},
		{"R4, AES-128, /V 4", fixtureAES128},
		{"R5, AES-256, /V 5", fixtureAES256R5},
		{"R6, AES-256, /V 5", fixtureAES256},
	}
}

// TestPDFEncryptFixturesOpen proves each fixture opens, walks one page, and
// decrypts the content stream and the font and Info strings it carries. A
// wrong key would fail the inflate or produce bytes that do not hold the
// drawn words.
func TestPDFEncryptFixturesOpen(t *testing.T) {
	for _, fixture := range encryptFixtures() {
		t.Run(fixture.name, func(t *testing.T) {
			src, err := decodeHex(fixture.hex)
			if err != nil {
				t.Fatalf("decodeHex: %v", err)
			}
			file, err := Open(t.Context(), src)
			if err != nil {
				t.Fatalf("Open: %v", err)
			}
			report, err := file.Info()
			if err != nil {
				t.Fatalf("Info: %v", err)
			}
			if report.Pages != 1 {
				t.Fatalf("pages %d, want 1", report.Pages)
			}
			content, err := file.Content(0)
			if err != nil {
				t.Fatalf("Content: %v", err)
			}
			if !bytes.Contains(content, []byte("(Hello Spectre) Tj")) {
				t.Fatalf("content does not draw the fixture words: %q", content)
			}
			text, err := file.ExtractText(t.Context(), 0)
			if err != nil {
				t.Fatalf("ExtractText: %v", err)
			}
			if !strings.Contains(text, "Hello Spectre") {
				t.Fatalf("text %q does not hold the fixture words", text)
			}
		})
	}
}

// decodeHex decodes one fixture constant.
func decodeHex(text string) ([]byte, error) {
	return hex.DecodeString(text)
}

// TestPDFEncryptCorruptKeyMaterialRefused proves the reader does not open a
// handler whose /O, /U, or /ID no longer matches the empty password. A
// corrupted entry is the failure mode a wrong key would produce, so the
// reader has to refuse rather than decrypt to noise.
func TestPDFEncryptCorruptKeyMaterialRefused(t *testing.T) {
	source, err := decodeHex(fixtureRC440)
	if err != nil {
		t.Fatalf("decodeHex: %v", err)
	}
	cases := []struct {
		name   string
		before string
		after  string
	}{
		{"corrupted O", "d46a06ca", "d46a06cb"},
		{"corrupted U", "69572911", "69572912"},
		{"corrupted ID", "<3737346239643632303339", "<3737346239643632303338"},
	}
	for _, testCase := range cases {
		t.Run(testCase.name, func(t *testing.T) {
			src := bytes.Replace(source, []byte(testCase.before), []byte(testCase.after), 1)
			if bytes.Equal(src, source) {
				t.Fatalf("fixture does not carry %q", testCase.before)
			}
			_, err := Open(t.Context(), src)
			wantJob(t, err, opEncrypt, errAccess)
		})
	}
}
